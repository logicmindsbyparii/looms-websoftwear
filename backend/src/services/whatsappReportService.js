function getTodayDateRange() {
  const start = new Date();
  start.setHours(0, 0, 0, 0);
  const end = new Date();
  end.setHours(23, 59, 59, 999);
  return { start, end };
}

function formatDateIST(date = new Date()) {
  return new Intl.DateTimeFormat('en-IN', {
    timeZone: 'Asia/Kolkata',
    day: '2-digit',
    month: '2-digit',
    year: 'numeric'
  }).format(date);
}

function formatTimeIST(date = new Date()) {
  return new Intl.DateTimeFormat('en-IN', {
    timeZone: 'Asia/Kolkata',
    hour: '2-digit',
    minute: '2-digit',
    hour12: true
  }).format(date);
}

/**
 * 1. Daily Production Report
 */
export async function generateDailyProductionReport() {
  const { start, end } = getTodayDateRange();
  const settings = await Settings.findOne() || { plantName: 'LOOMUS Advanced Weaving Facility' };
  const machines = await Machine.find();
  const todayLogs = await ProductionLog.find({
    createdAt: { $gte: start, $lte: end }
  });

  const totalMeters = todayLogs.reduce((acc, log) => acc + (Number(log.output) || 0), 0);
  const targetMeters = todayLogs.reduce((acc, log) => acc + (Number(log.target) || 75), 0) || (machines.length * 75);
  const variance = totalMeters - targetMeters;
  const runningCount = machines.filter(m => m.status === 'running').length;
  const totalCount = machines.length;

  // Top producing machine today
  const machineOutputMap = {};
  todayLogs.forEach(l => {
    machineOutputMap[l.machine] = (machineOutputMap[l.machine] || 0) + l.output;
  });
  const topMachineEntry = Object.entries(machineOutputMap).sort((a, b) => b[1] - a[1])[0];
  const topMachineText = topMachineEntry ? `${topMachineEntry[0]} (${topMachineEntry[1]}m)` : 'N/A';

  return `📊 *${settings.plantName.toUpperCase()}*
📋 *DAILY PRODUCTION REPORT*
📅 *Date:* ${formatDateIST()} | 🕒 *Time:* ${formatTimeIST()}
----------------------------------------
🏭 *Total Output Today:* *${totalMeters.toLocaleString()} m*
🎯 *Daily Target:* *${targetMeters.toLocaleString()} m*
📈 *Target Achievement:* *${targetMeters > 0 ? ((totalMeters / targetMeters) * 100).toFixed(1) : 0}%*
⚡ *Variance:* *${variance >= 0 ? `+${variance.toFixed(1)}m` : `${variance.toFixed(1)}m`}*
🟢 *Active Looms:* *${runningCount} / ${totalCount} Running*
🏆 *Top Producer:* *${topMachineText}*
----------------------------------------
✅ Generated by LOOMUS AI System`;
}

/**
 * 2. Shift-wise Production Report
 */
export async function generateShiftProductionReport(shiftName = 'Current') {
  const { start, end } = getTodayDateRange();
  const settings = await Settings.findOne() || { plantName: 'LOOMUS Advanced Weaving Facility' };
  const todayLogs = await ProductionLog.find({
    createdAt: { $gte: start, $lte: end }
  });

  const shifts = ['Morning', 'Evening', 'Night'];
  let shiftSummary = '';

  for (const s of shifts) {
    const sLogs = todayLogs.filter(l => (l.shift || '').toLowerCase().includes(s.toLowerCase()));
    const output = sLogs.reduce((acc, l) => acc + (Number(l.output) || 0), 0);
    const defects = sLogs.reduce((acc, l) => acc + (Number(l.defects) || 0), 0);
    shiftSummary += `• *${s} Shift:* ${output.toLocaleString()} m (Defects: ${defects})\n`;
  }

  const rollsCreatedToday = await Roll.countDocuments({ createdAt: { $gte: start, $lte: end } });

  return `⏱️ *${settings.plantName.toUpperCase()}*
📋 *SHIFT-WISE PRODUCTION REPORT*
📅 *Date:* ${formatDateIST()} | 🕒 *Time:* ${formatTimeIST()}
----------------------------------------
${shiftSummary.trim()}
----------------------------------------
📦 *Rolls Cut & Logged Today:* *${rollsCreatedToday} Rolls*
----------------------------------------
✅ Generated by LOOMUS AI System`;
}

